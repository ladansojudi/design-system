#!/usr/bin/env node
/**
 * AI package export — makes the design system consumable by LLMs / coding
 * agents (https://llmstxt.org convention).
 *
 * Outputs:
 *   public/llms.txt                    — short entry point: rules + links
 *   public/llms-full.txt               — everything in one file: rules, setup,
 *                                        theme CSS, every component doc + source
 *   public/theme.css                   — install-ready tokens (light + dark) and
 *                                        the Tailwind v4 @theme mapping, extracted
 *                                        from app/globals.css
 *   public/docs/components/<slug>.md   — the per-component docs, served as-is
 *
 *   public/eslint-plugin-s4e.mjs       — the lint guardrails, for consumer repos
 *
 * Sources: docs/components/*.md, eslint/eslint-plugin-s4e.mjs, components/ui/*.tsx, lib/utils.ts,
 * app/globals.css. Set SITE_URL to emit absolute links in llms.txt.
 *
 * Run manually: `npm run llms`
 * Auto-runs:   `npm run build` (via the prebuild script in package.json)
 */

const fs   = require("fs");
const path = require("path");

const ROOT      = path.resolve(__dirname, "..");
const DOCS_DIR  = path.join(ROOT, "docs", "components");
const UI_DIR    = path.join(ROOT, "components", "ui");
const PUBLIC    = path.join(ROOT, "public");
const SITE_URL  = (process.env.SITE_URL ?? "").replace(/\/$/, "");
const VERSION   = require(path.join(ROOT, "package.json")).version;

const url = (p) => `${SITE_URL}${p}`;

// ── Components (from the docs front-matter) ────────────────────────────────

const CATEGORY_ORDER = ["Atom", "Molecule", "Organism"];

function parseDoc(file) {
  const raw  = fs.readFileSync(path.join(DOCS_DIR, file), "utf8");
  const fm   = raw.match(/^---\n([\s\S]*?)\n---\n/);
  const meta = {};
  if (fm) {
    for (const line of fm[1].split("\n")) {
      const m = line.match(/^(\w+):\s*(.*)$/);
      if (m) meta[m[1]] = m[2].trim();
    }
  }
  const body    = fm ? raw.slice(fm[0].length) : raw;
  // First plain paragraph after the H1 (skipping callouts) is the summary.
  const summary = ((body.split(/\n#\s.+\n/)[1] ?? "").trim().split(/\n\n/).find((p) => !p.startsWith(">")) ?? "")
    .replace(/\s+/g, " ");
  return { file, slug: meta.slug ?? file.replace(/\.md$/, ""), meta, body: raw, summary };
}

const docs = fs
  .readdirSync(DOCS_DIR)
  .filter((f) => f.endsWith(".md") && f !== "README.md" && !f.startsWith("_"))
  .map(parseDoc)
  .sort((a, b) =>
    CATEGORY_ORDER.indexOf(a.meta.category) - CATEGORY_ORDER.indexOf(b.meta.category) ||
    a.meta.title.localeCompare(b.meta.title),
  );

for (const d of docs) {
  if (!fs.existsSync(path.join(UI_DIR, `${d.slug}.tsx`))) {
    console.error(`export-llms: docs/components/${d.file} has no components/ui/${d.slug}.tsx`);
    process.exit(1);
  }
}

// ── Theme CSS (tokens + Tailwind mapping, minus styleguide-only rules) ─────

// Split globals.css into top-level chunks (leading comments + one rule) so
// we can drop the ones that only style this styleguide site.
function topLevelChunks(css) {
  const chunks = [];
  let depth = 0, start = 0, i = 0;
  while (i < css.length) {
    if (css.startsWith("/*", i)) { i = css.indexOf("*/", i + 2) + 2; continue; }
    const ch = css[i];
    if (ch === "{") depth++;
    if (ch === "}" && --depth === 0) { chunks.push(css.slice(start, i + 1)); start = i + 1; }
    if (ch === ";" && depth === 0)   { chunks.push(css.slice(start, i + 1)); start = i + 1; }
    i++;
  }
  return chunks;
}

const selectorOf = (chunk) => chunk.replace(/\/\*[\s\S]*?\*\//g, "").trim().split("{")[0].trim();

const STYLEGUIDE_ONLY = [
  /^@import/,                 // the consumer brings their own Tailwind setup
  /^@layer base/,             // this site's body / border defaults
  /^\.ai-|^@keyframes ai-/,   // styleguide chrome animations
  /^\.ds-code/,               // Shiki code blocks
];

const themeCss = [
  `/* S4E Design System v${VERSION} — theme
 * Auto-generated by scripts/export-llms.js from app/globals.css — do not edit by hand.
 *
 * Requires Tailwind CSS v4. Import after Tailwind:
 *   @import "tailwindcss";
 *   @import "./theme.css";
 * Light: :root or [data-s4e-theme="light"]. Dark: .dark or [data-s4e-theme="dark"].
 */`,
  ...topLevelChunks(fs.readFileSync(path.join(ROOT, "app", "globals.css"), "utf8"))
    .filter((c) => !STYLEGUIDE_ONLY.some((re) => re.test(selectorOf(c))))
    .map((c) => c.replace(/^\s*\n/, "")),
].join("\n\n").replace(/\n{3,}/g, "\n\n") + "\n";

// ── Shared text ────────────────────────────────────────────────────────────

const RULES = `## Rules for AI agents

1. **Use the existing components.** Copy the source from \`/components/<slug>.tsx.txt\` into \`components/ui/<slug>.tsx\`. Don't recreate a component that already exists, and don't restyle it from scratch.
2. **Never hard-code colours, shadows or z-indexes.** Use the \`s4e-*\` tokens through Tailwind utilities (\`bg-s4e-surface-app\`, \`text-s4e-text-secondary\`, \`border-s4e-border-default\`, \`shadow-s4e-lg\`, \`z-modal\`). Every token is defined in \`theme.css\`.
3. **Prefer semantic tokens over scale primitives.** Borders: \`border-s4e-border-default\` / \`-strong\` / \`-focus\` / \`-error\`. Tints: \`bg-s4e-bg-subtle\`, \`bg-s4e-bg-{brand,info,success,warning,error}-subtle\`. Focus: \`ring-s4e-focus-ring\` (\`-error\` for destructive). Text: \`text-s4e-text-*\`. Surfaces: \`bg-s4e-surface-*\`. Use \`s4e-scale-<hue>-<step>\` / \`s4e-neutral-*\` primitives only when the hue itself is the meaning (severity, data series). Use \`text-s4e-text-disabled\` only for disabled controls; it fails contrast for normal text.
4. **Follow each component's "When to use / When not to use".** For example, a destructive confirm is a \`Modal\` with \`Button intent="destructive"\`, a vulnerability level is always \`SeverityBadge\`, and navigation is a link, not a \`Button\`.
5. **Accessibility is part of the API.** Pass \`label\` to form fields, \`aria-label\` to icon-only buttons and to \`RadioGroup\` / \`TabsList\`, and an \`aria-label\` with the takeaway to charts. Don't remove the focus styles.
6. **Respect the status.** \`deprecated\` components (Banner) must not be used in new code; follow the migration note. \`alpha\` components may change.
7. **Check "Known gaps"** in each doc before assuming a behaviour exists.
8. **Naming:** states are lowercase (\`state="error"\`), colour families are \`tone\` (not \`color\`).
9. **Lint your output.** Add [eslint-plugin-s4e](${url("/eslint-plugin-s4e.mjs")}) (\`s4e.configs.recommended\`): it rejects hard-coded colours and unlabeled icon-only buttons, and autofixes primitives to semantic tokens. Fix every error before finishing.`;

const SETUP = `## Setup

- **Requirements:** React 19, Tailwind CSS v4, \`clsx\`, \`tailwind-merge\` and \`lucide-react\`. \`Tabs\` has no extra deps; \`Modal\` uses \`react-dom\`'s \`createPortal\`.
- **Lint guardrails:** save [eslint-plugin-s4e.mjs](${url("/eslint-plugin-s4e.mjs")}) in your repo and add \`import s4e from "./eslint-plugin-s4e.mjs"\` + \`s4e.configs.recommended\` to \`eslint.config.mjs\` (flat config).
- **Tokens and theme:** add [theme.css](${url("/theme.css")}) after \`@import "tailwindcss";\`. Dark mode is enabled with \`.dark\` or \`[data-s4e-theme="dark"]\` on an ancestor.
- **\`cn()\` helper** at \`@/lib/utils\`:

\`\`\`ts
${fs.readFileSync(path.join(ROOT, "lib", "utils.ts"), "utf8").trim()}
\`\`\``;

const HEADER = `# S4E Design System

> React + Tailwind v4 component library and design tokens for the S4E security product (scans, assets, findings, severity). Version ${VERSION}. ${docs.length} copy-paste components (shadcn-style: you own the code), themed with \`s4e-*\` CSS variables in light and dark mode, targeting WCAG 2.2 AA and the WAI-ARIA Authoring Practices (remaining gaps are listed per component).`;

// ── llms-full.txt ──────────────────────────────────────────────────────────

const componentSections = docs.map((d) => {
  const src = fs.readFileSync(path.join(UI_DIR, `${d.slug}.tsx`), "utf8").trim();
  return [
    `<!-- ===== ${d.meta.title} (${d.slug}) ===== -->`,
    d.body.trim(),
    `### Source — \`components/ui/${d.slug}.tsx\``,
    "```tsx\n" + src + "\n```",
  ].join("\n\n");
});

const llmsFull = [
  HEADER,
  RULES,
  SETUP,
  `## Index\n\n${docs.map((d) => `- ${d.meta.title} (\`${d.slug}\`, ${d.meta.category}, ${d.meta.status})`).join("\n")}`,
  "## Theme CSS (`theme.css`)\n\n```css\n" + themeCss.trim() + "\n```",
  "## Components",
  ...componentSections,
].join("\n\n") + "\n";

// Rough size so agents (and humans) know what they're loading: ~4 chars/token.
const approxTokens = Math.round(llmsFull.length / 4 / 1000);

// ── llms.txt ───────────────────────────────────────────────────────────────

const byCategory = (cat) => docs.filter((d) => d.meta.category === cat);
const statusTag  = (d) => (d.meta.status && d.meta.status !== "stable" ? ` **[${d.meta.status}]**` : "");

const llmsTxt = [
  HEADER,
  RULES,
  SETUP,
  ...CATEGORY_ORDER.map((cat) => [
    `## ${cat}s`,
    byCategory(cat)
      .map((d) =>
        `- [${d.meta.title}](${url(`/docs/components/${d.slug}.md`)})${statusTag(d)}: ${d.meta.status === "deprecated" ? "Do not use in new code; see the migration note. " : ""}${d.summary} Source: [${d.slug}.tsx](${url(`/components/${d.slug}.tsx.txt`)})`)
      .join("\n"),
  ].join("\n\n")),
  `## Optional

- [llms-full.txt](${url("/llms-full.txt")}): every doc, the full theme CSS and every component's source in one file (~${approxTokens}k tokens)
- [Per-platform token exports](${url("/tokens/_all/tokens.css")}): CSS (light only), also [Swift](${url("/tokens/_all/tokens.swift")}) and [Android XML](${url("/tokens/_all/tokens.xml")})`,
].join("\n\n") + "\n";


// ── Write ──────────────────────────────────────────────────────────────────

const DOCS_OUT = path.join(PUBLIC, "docs", "components");
fs.mkdirSync(DOCS_OUT, { recursive: true });
for (const d of docs) fs.writeFileSync(path.join(DOCS_OUT, `${d.slug}.md`), d.body);

fs.writeFileSync(path.join(PUBLIC, "theme.css"), themeCss);
fs.copyFileSync(path.join(ROOT, "eslint", "eslint-plugin-s4e.mjs"), path.join(PUBLIC, "eslint-plugin-s4e.mjs"));
fs.writeFileSync(path.join(PUBLIC, "llms.txt"), llmsTxt);
fs.writeFileSync(path.join(PUBLIC, "llms-full.txt"), llmsFull);

const kb = (s) => `${Math.round(Buffer.byteLength(s) / 1024)} KB`;
console.log(`  llms.txt:      ${kb(llmsTxt)}`);
console.log(`  llms-full.txt: ${kb(llmsFull)} (~${approxTokens}k tokens)`);
console.log(`  theme.css:     ${kb(themeCss)}`);
console.log(`✓ export-llms — ${docs.length} components → public/llms.txt, public/llms-full.txt, public/theme.css, public/docs/components/`);
